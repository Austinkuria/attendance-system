const mongoose = require("mongoose");
const dotenv = require("dotenv");
const crypto = require("crypto");
const path = require("path");

dotenv.config({ path: path.join(__dirname, "../.env") });

const User = require("../models/User");
const Unit = require("../models/Unit");
const Session = require("../models/Session");
const Attendance = require("../models/Attendance");
const Feedback = require("../models/Feedback");
const { generateManualPin, generateRotatingQrPayload, verifyRotatingQrPayload } = require("../utils/dynamicQrUtils");
const { generateCsvReport, generatePdfReport } = require("../utils/reportGenerator");

async function runTests() {
  console.log("--- Testing Dynamic QR & PIN Utilities ---");
  const pin = generateManualPin();
  console.log("Generated Manual PIN:", pin, "Length:", pin.length);
  if (pin.length !== 6) throw new Error("PIN must be 6 characters");

  const mockSession = {
    _id: new mongoose.Types.ObjectId(),
    qr_secret: crypto.randomBytes(32).toString("hex"),
    manual_pin: pin
  };

  const rotating = await generateRotatingQrPayload(mockSession);
  console.log("Rotating QR Token Generated:", rotating.qrToken.slice(0, 30) + "...");
  console.log("Slot:", rotating.slot, "Seconds Remaining:", rotating.secondsRemaining);

  const verification = verifyRotatingQrPayload(mockSession, rotating.qrToken);
  console.log("Verification Result:", verification);
  if (!verification.valid) throw new Error("Rotating QR verification failed");

  console.log("--- Testing PDF and CSV Report Generators ---");
  const mockRecords = [
    {
      session: {
        startTime: new Date(),
        unit: { code: "SE301", name: "Mobile and Web Application Architecture" }
      },
      status: "Present",
      check_in_method: "QR_SCAN",
      attendedAt: new Date()
    },
    {
      session: {
        startTime: new Date(Date.now() - 86400000),
        unit: { code: "SE302", name: "Distributed Systems" }
      },
      status: "Late",
      check_in_method: "MANUAL_PIN",
      attendedAt: new Date(Date.now() - 86400000)
    }
  ];

  const studentInfo = {
    fullName: "Alex Kuria",
    regNumber: "SCT211-0012/2023",
    courseName: "BSc. Software Engineering"
  };

  const csv = generateCsvReport(mockRecords, studentInfo);
  console.log("CSV Generated Length:", csv.length);
  if (!csv.includes("Alex Kuria") || !csv.includes("SE301")) throw new Error("CSV generation invalid");

  const pdfBuffer = generatePdfReport(mockRecords, studentInfo);
  console.log("PDF Buffer Generated Bytes:", pdfBuffer.length);
  const pdfHeader = pdfBuffer.slice(0, 8).toString("utf-8");
  console.log("PDF Header:", pdfHeader.trim());
  if (!pdfHeader.startsWith("%PDF-1.4")) throw new Error("Invalid PDF format");

  console.log("ALL BACKEND TEST CHECKS PASSED!");
}

runTests()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error("Test failed:", err);
    process.exit(1);
  });
